/**
 * src/modules/voice-core/api/sarvam/tts.ts
 * ─────────────────────────────────────────────────────────────────────────────
 * POST /api/voice/sarvam/tts — Bulbul text-to-speech, one request per reply
 * sentence. Serves the chat window's turn-based VOICE CHAT (surface
 * "voice_chat", the default: Voice Chat provider / TTS model / speaker).
 * The realtime voice agent streams through the Bulbul WebSocket relay
 * instead; surface "realtime" remains accepted for older clients.
 *
 * The ONLY data that crosses the Sarvam boundary here is the answer text to
 * be spoken (already generated by the platform's own chat + RAG). The
 * provider returns 16 kHz WAV which it strips to raw PCM16 — the shared
 * playback-queue contract (audio/octet-stream), so the ElevenLabs-mode client
 * machinery works unchanged.
 *
 * Guards: SARVAM_TTS_RATE (60/min/org) + 2,000-char platform cap (2,500
 * vendor) + planGuard("tts") + server-side re-resolution. Studio previews
 * use SARVAM_PREVIEW_RATE and the 300-char cap.
 */

import { NextRequest, NextResponse } from "next/server";
import { ensureMigrated } from "@/lib/db/migrate";
import { query as dbQuery } from "@/lib/db";
import { planGuard } from "@/lib/plan-guard";
import { hit, rateLimitResponse, SARVAM_TTS_RATE, SARVAM_PREVIEW_RATE } from "@/lib/rate-limit";
import {
  SARVAM_TTS_MAX_CHARS,
  SARVAM_PREVIEW_MAX_CHARS,
  SARVAM_TTS_SAMPLE_RATE_HZ,
  isSupportedSarvamTTSModel,
  isSupportedSarvamSpeaker,
  isValidUuid,
} from "../../model-catalog";
import { VoiceProviderFactory } from "../../factory";
import { SarvamVoiceError } from "../../providers/sarvam";
import { logTtsUsage } from "../../metering";
import { VoiceConfigResolutionError, resolveVoiceConfigCached } from "../../resolve";
import { sanitizeTtsText } from "../../tts-text";
import { embedVoiceGuard } from "../elevenlabs/embed-auth";

export async function postSarvamTts(request: NextRequest): Promise<NextResponse | Response> {
  try {
    await ensureMigrated();

    const body = await request.json().catch(() => null) as Record<string, unknown> | null;
    if (!body) {
      return NextResponse.json({ error: "JSON body required." }, { status: 400 });
    }

    const kbId = typeof body.kbId === "string" ? body.kbId.trim() : null;
    const text = typeof body.text === "string" ? body.text : "";
    const preview = body.preview === true;

    if (!text.trim()) {
      return NextResponse.json({ error: "text is required." }, { status: 400 });
    }

    // Same speakable-text discipline as the ElevenLabs route: strip citations
    // + markdown BEFORE caps, metering, and the vendor call so metering
    // reflects exactly what was spoken.
    const speakableText = sanitizeTtsText(text);
    if (!speakableText) {
      return NextResponse.json(
        { error: "text contains nothing speakable after removing citations and markdown." },
        { status: 400 },
      );
    }

    const maxChars = preview ? SARVAM_PREVIEW_MAX_CHARS : SARVAM_TTS_MAX_CHARS;
    if (speakableText.length > maxChars) {
      return NextResponse.json(
        { error: `Text too long (${speakableText.length} chars). Maximum is ${maxChars} per request.` },
        { status: 413 },
      );
    }

    if (!kbId || !isValidUuid(kbId)) {
      return NextResponse.json({ error: "A valid kbId is required." }, { status: 400 });
    }

    // Embed-authenticated callers (clr_ API key): validate the key/KB
    // pairing. No hourly-increment — the dedicated TTS bucket already
    // throttles per org.
    const embedDenied = await embedVoiceGuard(request, kbId);
    if (embedDenied) return embedDenied;

    const orgRows = await dbQuery<{ org_id: string; agent_id: string }>(
      `SELECT a.org_id, a.id AS agent_id FROM agents a JOIN knowledge_bases kb ON kb.agent_id = a.id WHERE kb.id = $1`,
      [kbId],
    );
    const orgId = orgRows[0]?.org_id ?? null;
    const agentId = orgRows[0]?.agent_id ?? null;

    {
      const ip = request.headers.get("x-forwarded-for")?.split(",")[0]?.trim()
        ?? request.headers.get("x-real-ip") ?? "unknown";
      const bucket = preview ? "sv-tts-preview" : "sv-tts";
      const rate = preview ? SARVAM_PREVIEW_RATE : SARVAM_TTS_RATE;
      const gate = hit(
        `${bucket}:${orgId ? `org:${orgId}` : `ip:${ip}`}`,
        rate.limit,
        rate.windowMs,
      );
      if (!gate.allowed) {
        const rl = rateLimitResponse(gate.retryAfterSec, "Text-to-speech rate limit reached. Please slow down.");
        return NextResponse.json(rl.body, { status: rl.status, headers: rl.headers });
      }
    }

    if (orgId) {
      // Rolling-24 h voice budget shared with ElevenLabs (provider-agnostic
      // max_tts_chars_day column — one pool per org).
      const ttsGuard = await planGuard(orgId, "tts");
      if (!ttsGuard.allowed) {
        const blocked = ttsGuard as { reason: string };
        return NextResponse.json(
          { error: "plan_limit_exceeded", code: "tts_limit_reached", message: blocked.reason },
          { status: 402 },
        );
      }
    }

    // Server-side re-resolution: client-suggested speaker/model are advisory.
    // Cached for 5 s — this route fires per sentence. Realtime axis: the
    // pipeline sessions bootstrap on the realtime purpose axis, so the hot
    // paths must agree or cross-axis orgs 409 on every sentence.
        // scope:"draft" — the authenticated agent preview resolves against
    // the CURRENT Main-branch draft instead of the immutable published
    // version (KB overrides apply; the LIVE collection is searched).
    const surface = body.surface === "realtime" ? "realtime" : "voice_chat";
    const resolved = await resolveVoiceConfigCached({ kbId, surface, ...(body?.scope === "draft" ? { preferDraft: true } : {}) });
    const surfaceProvider = surface === "voice_chat" ? resolved.voiceProvider : resolved.realtimeProvider;
    if (surfaceProvider !== "sarvam" || !resolved.sarvam) {
      return NextResponse.json(
        { error: "Voice provider is not Sarvam for this knowledge base.", provider: surfaceProvider },
        { status: 409 },
      );
    }

    const model = typeof body.model === "string" && isSupportedSarvamTTSModel(body.model)
      ? body.model
      : resolved.sarvam.voiceChatTtsModel;
    const speaker = typeof body.speaker === "string" && isSupportedSarvamSpeaker(body.speaker)
      ? body.speaker.trim().toLowerCase()
      : resolved.sarvam.voiceChatSpeaker;
    const language =
      typeof body.language === "string" && body.language ? body.language : resolved.sarvam.language;
    const speed = typeof body.speed === "number" && Number.isFinite(body.speed)
      ? Math.min(2, Math.max(0.5, body.speed))
      : undefined;

    const voiceService = VoiceProviderFactory.getVoiceService({ provider: "sarvam" });

    const startedAt = Date.now();
    const audioResponse = await voiceService.speak({
      text: speakableText,
      voiceId: speaker,
      modelId: model,
      // The provider parses the numeric sample rate out of this descriptor.
      outputFormat: `pcm_${SARVAM_TTS_SAMPLE_RATE_HZ}`,
      languageCode: language,
      ...(speed != null ? { speed } : {}),
    });
    const latencyMs = Date.now() - startedAt;

    // Meter from the request fact (character count of what was actually
    // spoken) — cheap and exact.
    await logTtsUsage({
      orgId,
      kbId,
      agentId,
      model,
      latencyMs,
      characters: speakableText.length,
      preview,
      provider: "sarvam",
    });

    // Bulbul audio arrives as a complete buffer (WAV → PCM stripped inside
    // the provider, or verbatim WAV on a non-canonical container). The
    // provider already set the honest content type — pass through with the
    // model/speaker advisory headers the shared client reads.
    const contentType = audioResponse.headers.get("Content-Type") ?? "application/octet-stream";
    return new Response(audioResponse.body, {
      status: 200,
      headers: {
        "Content-Type": contentType,
        "Cache-Control": "no-store",
        "X-Sarvam-Model": model,
        "X-Sarvam-Speaker": speaker,
      },
    });
  } catch (error) {
    console.error("[sarvam-tts] post:", error);
    if (error instanceof SarvamVoiceError) {
      return NextResponse.json({ error: error.message }, { status: 502 });
    }
    if (error instanceof VoiceConfigResolutionError) {
      return NextResponse.json({ error: error.message }, { status: 400 });
    }
    return NextResponse.json({ error: (error as Error).message }, { status: 500 });
  }
}
